-- =============================================================================
-- Dienstplaner: Schichtregeln
-- Eine Regel = Position + Uhrzeit + Wochentage (+ Anzahl, optional "nur Leitung").
-- Ersetzt die Kombination aus Schichtanforderungen (Schienen) + Positions-Matrix.
-- Idempotent: kann gefahrlos mehrfach ausgeführt werden (neue UND bestehende DB).
-- Führe dieses Script in deiner Supabase-Datenbank (SQL Editor) aus.
-- =============================================================================

-- 1) Wöchentlich wiederkehrende Regeln
create table if not exists dienstplan_shift_rules (
  id bigint generated by default as identity primary key,
  position text not null,
  -- true: nur Projektionsleitung (bei "Projektion" zählt die Leitung sonst gleichwertig mit)
  require_leader boolean not null default false,
  start_time time not null,
  end_time time not null,
  -- 0 = Sonntag ... 6 = Samstag
  weekdays smallint[] not null
    check (cardinality(weekdays) > 0 and weekdays <@ array[0,1,2,3,4,5,6]::smallint[]),
  required_count smallint not null default 1
    check (required_count between 1 and 10),
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2) Tages-Anpassungen (ersetzen an dem Tag alle Wochenregeln)
alter table dienstplan_position_requirements
  add column if not exists require_leader boolean not null default false,
  add column if not exists required_count smallint not null default 1;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'dienstplan_position_requirements_count_check'
  ) then
    -- 0 = Platzhalter "kein Bedarf an diesem Tag"
    alter table dienstplan_position_requirements
      add constraint dienstplan_position_requirements_count_check
      check (required_count between 0 and 10);
  end if;
end $$;

-- 3) Offene Slots merken, ob nur die Projektionsleitung infrage kommt
alter table dienstplan_planned_slots
  add column if not exists require_leader boolean not null default false;

-- 4) Bestehende Wochentag-Anforderungen als Regeln übernehmen (nur einmalig, wenn noch keine Regel existiert)
insert into dienstplan_shift_rules (position, require_leader, start_time, end_time, weekdays, required_count, note)
select
  grouped.position,
  lower(grouped.position) = 'projektionsleitung',
  t.start_time,
  t.end_time,
  array_agg(grouped.weekday order by grouped.weekday)::smallint[],
  grouped.cnt::smallint,
  grouped.note
from (
  select track_key, position, note, weekday, least(count(*), 10) as cnt
  from dienstplan_weekday_position_requirements
  group by track_key, position, note, weekday
) as grouped
join dienstplan_shift_tracks t on t.track_key = grouped.track_key
where not exists (select 1 from dienstplan_shift_rules)
group by grouped.track_key, grouped.position, grouped.note, grouped.cnt, t.start_time, t.end_time;
