  id bigint generated by default as identity primary key,
  slot_date date not null,
  position text,
  track_key text references dienstplan_shift_tracks(track_key) on delete set null,
  start_time time not null,
  end_time time not null,
  note text,
  source text not null default 'manual',
  assigned_employee_id bigint references dienstplan_employees(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_dienstplan_planned_slots_date
  on dienstplan_planned_slots(slot_date);
create index if not exists idx_dienstplan_planned_slots_open
  on dienstplan_planned_slots(slot_date)
  where assigned_employee_id is null;

