-- Dienstplaner: Vorplanung (geplante, evtl. unbesetzte Slots)
-- Wenn assigned_employee_id NULL ist, ist der Slot unbesetzt (rot).
-- Beim Besetzen wird der Slot mit assigned_employee_id verknüpft und eine Schicht
-- in dienstplan_shifts angelegt. Die Slots dienen als Grundgerüst für die KI.
