-- Fallback: Ergänze fehlende ID-Spalte und Primärschlüssel, falls die Tabelle bereits ohne ID existiert
do $$
begin
  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'roles'
      and column_name = 'id'
  ) then
    alter table roles add column id bigint generated by default as identity;
  end if;

  if not exists (
    select 1
    from information_schema.table_constraints tc
    join information_schema.key_column_usage kcu
      on tc.constraint_name = kcu.constraint_name
     and tc.table_schema = kcu.table_schema
     and tc.table_name = kcu.table_name
    where tc.table_schema = 'public'
      and tc.table_name = 'roles'
      and tc.constraint_type = 'PRIMARY KEY'
      and kcu.column_name = 'id'
  ) then
    alter table roles add primary key (id);
  end if;
end $$;

-- Fallback: db_heartbeat ID auf Identity-Default setzen, wenn noch keine Identity vorhanden ist.
-- Wichtig: column_default ist bei Identity-Spalten immer NULL (Postgres trackt das über
-- is_identity, nicht über column_default) - daher hier explizit auf is_identity = 'NO' prüfen,
-- sonst würde dieser Block bei jedem Lauf erneut feuern und mit einem Fehler abbrechen.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'db_heartbeat'
      and column_name = 'id'
      and is_identity = 'NO'
  ) then
    alter table db_heartbeat alter column id add generated by default as identity;
  end if;
end $$;

