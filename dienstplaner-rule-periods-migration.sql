-- =============================================================================
-- Dienstplaner: Zeiträume mit abweichenden Schichtregeln (z. B. Ferien)
-- Regeln mit period_id gelten nur im Zeitraum und ersetzen dort die Standardregeln.
-- Voraussetzung: dienstplaner-shift-rules-migration.sql wurde bereits ausgeführt.
-- Idempotent: kann gefahrlos mehrfach ausgeführt werden.
-- =============================================================================

create table if not exists dienstplan_rule_periods (
  id bigint generated by default as identity primary key,
  name text not null,
  start_date date not null,
  end_date date not null,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create index if not exists idx_dienstplan_rule_periods_dates
  on dienstplan_rule_periods(start_date, end_date);

-- Regeln eines gelöschten Zeitraums werden mitgelöscht
alter table dienstplan_shift_rules
  add column if not exists period_id bigint references dienstplan_rule_periods(id) on delete cascade;

create index if not exists idx_dienstplan_shift_rules_period
  on dienstplan_shift_rules(period_id);
